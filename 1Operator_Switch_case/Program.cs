using System;

public class Program

{
    public static void Main()
    {
        ФункцияИзмерения(-4);
        ФункцияИзмерения(50);
        ФункцияИзмерения(133);
        void ФункцияИзмерения(int измерения)
        {
            switch (измерения)
            {
                case < 0:
                case > 100:
                    Console.WriteLine($"Значение измерения меньше 0, либо больше 100 и равно {измерения};\n");
                    break;

                default:
                    Console.WriteLine($"Значение измерения равно {измерения}\n");
                    break;
            }
        }
    }
}
//### Описание примеров

//**Пример 1 * *

//В данном примере реализован ввод значения с консоли с последующей обработкой с помощью оператора `switch`. Переменная `userInput` получает значение, введённое пользователем, после чего происходит проверка этого значения по нескольким вариантам (`case`).

//Оператор `switch` сравнивает введённое число с конкретными значениями (5, 15, 20, 6), а также содержит условие (`case > 20`). В зависимости от совпадения выполняется соответствующий блок кода. Если ни одно условие не выполняется, срабатывает блок `default`, который обрабатывает все остальные случаи.

//Таким образом, пример демонстрирует использование `switch` для выбора действия на основе введённого значения.

